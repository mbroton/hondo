import { useState } from "react"
import { Link } from "react-router"
import {
  RiArrowDownLine,
  RiArrowUpLine,
  RiBarChartLine,
  RiCalendarLine,
  RiFlashlightLine,
  RiMoneyDollarCircleLine,
} from "@remixicon/react"
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card"
import {
  Select,
  SelectContent,
  SelectGroup,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select"
import { Skeleton } from "@/components/ui/skeleton"
import {
  Table,
  TableBody,
  TableCell,
  TableFooter,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table"
import {
  Empty,
  EmptyContent,
  EmptyDescription,
  EmptyHeader,
  EmptyMedia,
  EmptyTitle,
} from "@/components/ui/empty"
import { Alert, AlertDescription } from "@/components/ui/alert"
import { Button } from "@/components/ui/button"
import { ErrorCard } from "@/components/error-card"
import { PageHeading } from "@/components/page-heading"
import { useWorkspace } from "@/hooks/use-workspace"
import { useUsage } from "@/lib/api/queries"
import {
  currentMonth,
  formatTokens,
  formatUsd,
  recentMonths,
} from "@/lib/format"

export default function UsagePage() {
  const { workspace, isPending, isError } = useWorkspace()
  const workspaceId = workspace?.id ?? null
  const [month, setMonth] = useState(currentMonth)
  const usage = useUsage(workspaceId, month)
  const months = recentMonths()
  const summary = usage.data
  const models = summary?.models ?? []
  const input = models.reduce((total, model) => total + model.input_tokens, 0)
  const output = models.reduce((total, model) => total + model.output_tokens, 0)
  const requests = models.reduce((total, model) => total + model.requests, 0)
  const loading = isPending || usage.isPending
  const metrics = [
    {
      label: "Total cost",
      value: formatUsd(summary?.total_cost_usd ?? "0"),
      note: "Estimated cost in USD",
      icon: RiMoneyDollarCircleLine,
    },
    {
      label: "Model requests",
      value: formatTokens(requests),
      note: "Across all models",
      icon: RiFlashlightLine,
    },
    {
      label: "Input tokens",
      value: formatTokens(input),
      note: "Sent to your models",
      icon: RiArrowUpLine,
    },
    {
      label: "Output tokens",
      value: formatTokens(output),
      note: "Generated by your models",
      icon: RiArrowDownLine,
    },
  ]

  return (
    <div className="flex flex-col gap-7">
      <PageHeading
        title="Usage"
        description="A clear view of what your team uses and what it costs."
      >
        <Select
          value={month}
          onValueChange={(next) => {
            if (next) setMonth(next)
          }}
        >
          <SelectTrigger aria-label="Usage month" className="w-48">
            <RiCalendarLine aria-hidden="true" />
            <SelectValue>
              {months.find((option) => option.value === month)?.label}
            </SelectValue>
          </SelectTrigger>
          <SelectContent>
            <SelectGroup>
              {months.map((option) => (
                <SelectItem key={option.value} value={option.value}>
                  {option.label}
                </SelectItem>
              ))}
            </SelectGroup>
          </SelectContent>
        </Select>
      </PageHeading>
      {isError || (!isPending && !workspace) ? (
        <ErrorCard title="Could not load your workspace" />
      ) : usage.isError ? (
        <ErrorCard
          title="Could not load usage"
          description="Usage for this month is unavailable. Try again to get the latest totals."
          onRetry={() => void usage.refetch()}
          retrying={usage.isFetching}
        />
      ) : (
        <>
          <div
            className="grid grid-cols-2 gap-3 sm:gap-4 @4xl/main:grid-cols-4"
            aria-busy={loading}
            aria-label="Monthly usage summary"
          >
            {metrics.map(({ label, value, note, icon: Icon }) => (
              <Card
                key={label}
                className="gap-4 [--card-spacing:--spacing(4)] sm:gap-6 sm:[--card-spacing:--spacing(6)]"
              >
                <CardHeader>
                  <div className="flex items-center justify-between gap-3">
                    <p className="text-xs text-muted-foreground sm:text-sm">
                      {label}
                    </p>
                    <Icon
                      className="size-4 text-muted-foreground"
                      aria-hidden="true"
                    />
                  </div>
                </CardHeader>
                <CardContent className="flex flex-col gap-2">
                  {loading ? (
                    <Skeleton className="h-9 w-28" />
                  ) : (
                    <p className="text-xl font-semibold tracking-tight break-all tabular-nums sm:text-3xl">
                      {value}
                    </p>
                  )}
                  <p className="text-xs text-muted-foreground">{note}</p>
                </CardContent>
              </Card>
            ))}
          </div>
          {summary?.has_unpriced && (
            <Alert>
              <AlertDescription>
                Some models do not have a price yet. The total includes only
                models with known prices.
              </AlertDescription>
            </Alert>
          )}
          <Card className="gap-0 pb-0">
            <CardHeader className="pb-6">
              <CardTitle>Usage by model</CardTitle>
              <CardDescription>
                Requests, tokens, and cost for the selected month.
              </CardDescription>
            </CardHeader>
            {!loading && !models.length ? (
              <Empty className="min-h-72 border-t">
                <EmptyHeader>
                  <EmptyMedia variant="icon">
                    <RiBarChartLine />
                  </EmptyMedia>
                  <EmptyTitle>No usage this month</EmptyTitle>
                  <EmptyDescription>
                    Usage appears here after Hondo responds in Slack. You can
                    also select another month.
                  </EmptyDescription>
                </EmptyHeader>
                <EmptyContent>
                  <Button
                    variant="outline"
                    nativeButton={false}
                    render={<Link to="/activity" />}
                  >
                    View activity
                  </Button>
                </EmptyContent>
              </Empty>
            ) : (
              <Table aria-label="Monthly usage by model" aria-busy={loading}>
                <TableHeader>
                  <TableRow className="bg-muted/40">
                    <TableHead>Model</TableHead>
                    <TableHead className="hidden text-right @3xl/main:table-cell">
                      Requests
                    </TableHead>
                    <TableHead className="hidden text-right @3xl/main:table-cell">
                      Input tokens
                    </TableHead>
                    <TableHead className="hidden text-right @3xl/main:table-cell">
                      Output tokens
                    </TableHead>
                    <TableHead className="text-right">Cost</TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {loading
                    ? Array.from({ length: 3 }, (_, index) => (
                        <TableRow key={index}>
                          {Array.from({ length: 5 }, (_, cell) => (
                            <TableCell
                              key={cell}
                              className={
                                cell > 0 && cell < 4
                                  ? "hidden @3xl/main:table-cell"
                                  : undefined
                              }
                            >
                              <Skeleton className="h-5 w-full min-w-16" />
                            </TableCell>
                          ))}
                        </TableRow>
                      ))
                    : models.map((model) => (
                        <TableRow key={`${model.provider}/${model.model}`}>
                          <TableCell className="whitespace-normal">
                            <div className="flex flex-col gap-1">
                              <span className="font-medium break-all">
                                {model.model}
                              </span>
                              <span className="text-xs text-muted-foreground">
                                {model.provider}
                              </span>
                              <span className="text-xs text-muted-foreground @3xl/main:hidden">
                                {formatTokens(model.requests)} requests
                              </span>
                              <span className="text-xs text-muted-foreground @3xl/main:hidden">
                                {formatTokens(model.input_tokens)} in /{" "}
                                {formatTokens(model.output_tokens)} out
                              </span>
                            </div>
                          </TableCell>
                          <TableCell className="hidden text-right tabular-nums @3xl/main:table-cell">
                            {formatTokens(model.requests)}
                          </TableCell>
                          <TableCell className="hidden text-right tabular-nums @3xl/main:table-cell">
                            {formatTokens(model.input_tokens)}
                          </TableCell>
                          <TableCell className="hidden text-right tabular-nums @3xl/main:table-cell">
                            {formatTokens(model.output_tokens)}
                          </TableCell>
                          <TableCell className="text-right tabular-nums">
                            <div className="flex flex-col items-end gap-2">
                              <span className="font-medium">
                                {model.cost_usd === null
                                  ? "Unpriced"
                                  : formatUsd(model.cost_usd)}
                              </span>
                              {model.cost_usd !== null &&
                                Number(summary?.total_cost_usd) > 0 && (
                                  <div
                                    className="h-1 w-16 overflow-hidden rounded-full bg-muted"
                                    aria-hidden="true"
                                  >
                                    <div
                                      className="h-full rounded-full bg-primary"
                                      style={{
                                        width: `${Math.min(100, (Number(model.cost_usd) / Number(summary?.total_cost_usd)) * 100)}%`,
                                      }}
                                    />
                                  </div>
                                )}
                            </div>
                          </TableCell>
                        </TableRow>
                      ))}
                </TableBody>
                {!loading && summary && (
                  <TableFooter>
                    <TableRow>
                      <TableCell>Total</TableCell>
                      <TableCell className="hidden text-right tabular-nums @3xl/main:table-cell">
                        {formatTokens(requests)}
                      </TableCell>
                      <TableCell className="hidden text-right tabular-nums @3xl/main:table-cell">
                        {formatTokens(input)}
                      </TableCell>
                      <TableCell className="hidden text-right tabular-nums @3xl/main:table-cell">
                        {formatTokens(output)}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {formatUsd(summary.total_cost_usd)}
                      </TableCell>
                    </TableRow>
                  </TableFooter>
                )}
              </Table>
            )}
          </Card>
          <p className="text-xs leading-5 text-muted-foreground">
            Usage is grouped by calendar month in UTC. Costs are estimates based
            on model pricing.
          </p>
        </>
      )}
    </div>
  )
}
